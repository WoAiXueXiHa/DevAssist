// 在 scripts.check_migration 创建的隔离 fixture 上检查真实浏览器与 Go API。
import { chromium, expect } from '@playwright/test';
const base = process.argv[2];
if (!base) throw new Error('缺少隔离验收前端地址');
const browser = await chromium.launch({ headless: true, args: ['--no-sandbox'] });
const checks = [];
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto(`${base}/login`);
  await page.getByLabel('用户名', { exact: true }).fill('u');
  await page.getByLabel('密码', { exact: true }).fill('password123');
  await page.getByRole('button', { name: /^登\s*录$/ }).click();
  await expect(page.getByText('智能技术支持', { exact: true })).toBeVisible();
  checks.push('客户登录经 Go');
  await page.getByPlaceholder('描述你的问题…').fill('浏览器中文🙂测试');
  await page.getByRole('button', { name: /^发\s*送$/ }).click();
  await expect(page.getByText('中文🙂答案', { exact: false })).toBeVisible();
  await expect(page.getByRole('button', { name: /^发\s*送$/ })).toBeEnabled();
  checks.push('中文 SSE 完成');
  await page.getByRole('button', { name: /转人工/ }).first().click();
  await expect(page.getByText(/已为你转接人工技术支持/)).toBeVisible();
  checks.push('反馈建单与转人工');
  await page.getByRole('link', { name: '我的会话' }).click();
  await page.locator('.ant-list-item').filter({ hasText: 'doc_qa' }).first().click();
  await expect(page.getByText('人工模式 · 你的消息将直达技术支持')).toBeVisible();
  await page.getByPlaceholder('向技术支持补充信息…').fill('浏览器补充 13812345678');
  await page.getByRole('button', { name: /^发\s*送$/ }).click();
  await expect(page.getByText('浏览器补充 138****5678', { exact: true })).toBeVisible();
  checks.push('会话追加与原脱敏');
  await page.getByRole('link', { name: '文档中心' }).click();
  await expect(page.locator('.md')).not.toBeEmpty();
  checks.push('文档正文');
  await page.getByRole('link', { name: '我的工单' }).click();
  await expect(page.locator('.ant-table-tbody tr').first()).toBeVisible();
  checks.push('客户工单');
  await page.getByRole('button', { name: /^退\s*出$/ }).click();
  await page.getByLabel('用户名', { exact: true }).fill('staff');
  await page.getByLabel('密码', { exact: true }).fill('password123');
  await page.getByRole('button', { name: /^登\s*录$/ }).click();
  await expect(page.getByText('工单列表', { exact: true })).toBeVisible();
  await page.locator('.ant-table-tbody tr').filter({ hasText: 'initialticket' }).click();
  await expect(page.getByText('人工回复客户', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: /生成 AI 建议回复/ }).click();
  await expect(page.getByPlaceholder('编辑回复内容，发送后客户可在「我的会话」中看到')).toHaveValue('推荐回复：请补充调用日志。');
  await page.getByRole('button', { name: '发送回复给客户' }).click();
  await expect(page.getByText('已回复客户（客户可在「我的会话」看到）')).toBeVisible();
  checks.push('工作台详情、建议与人工回复');
  await page.getByRole('link', { name: '运营指标' }).click();
  await expect(page.getByText('会话总数', { exact: true })).toBeVisible();
  checks.push('指标数据');
  // 小屏只验证页面仍能加载，不将其写成全量布局优化验收。
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(`${base}/`);
  await expect(page.getByPlaceholder('描述你的问题…')).toBeVisible();
  checks.push('390px 聊天入口可加载');
  await page.getByPlaceholder('描述你的问题…').fill('__fail__');
  await page.getByRole('button', { name: /^发\s*送$/ }).click();
  await expect(page.getByText('AI 服务暂不可用，请稍后重试', { exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: /^发\s*送$/ })).toBeEnabled();
  checks.push('HTTP 502 中文提示与发送状态复原');
  if (errors.length) throw new Error(`浏览器脚本异常: ${errors.join('; ')}`);
  console.log(JSON.stringify({ passed: true, checks }));
  await context.close();
} finally {
  await browser.close();
}
